#!/usr/bin/env python3
"""Rebuild alliance service-area shapes from Census 2020 ZCTA boundaries.

Reads alliance ZIPs from assets/zip-routing.js. Non-alliance ZIPs and the
unlisted distance assignments are not drawn. A ZIP listed under two offices
is part of both shapes.

Requires: pip install shapely pyshp

The Census file is the 2020 cartographic boundary, 1:500,000:
https://www2.census.gov/geo/tiger/GENZ2020/shp/cb_2020_us_zcta520_500k.zip

Example:
  python3 tools/build-service-areas.py --shp /tmp/zcta/cb_2020_us_zcta520_500k.shp
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import shapefile
from shapely import make_valid, set_precision
from shapely.geometry import mapping, shape
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parent.parent
ROUTING = ROOT / "assets" / "zip-routing.js"
GEOJSON = ROOT / "assets" / "service-areas.geojson"
LOADER = ROOT / "assets" / "service-areas.js"
# Stay under the 300 KB budget with room for the JS wrapper.
MAX_BYTES = 280_000


def load_alliance(path: Path) -> dict:
    text = path.read_text()
    marker = "const ZIP_ROUTING = "
    start = text.find(marker)
    if start < 0:
        raise SystemExit("Could not read ZIP_ROUTING from " + str(path))
    data, _end = json.JSONDecoder().raw_decode(text[start + len(marker) :])
    by_office = {office: [] for office in data["offices"]}
    for zip_code, offices in data["allianceZips"].items():
        for office in offices:
            if office not in by_office:
                raise SystemExit("Alliance ZIP " + zip_code + " names unknown office " + office)
            by_office[office].append(zip_code)
    return by_office


def load_zctas(shp_path: Path, wanted: set[str]) -> dict:
    reader = shapefile.Reader(str(shp_path))
    found = {}
    for record, geometry in zip(reader.iterRecords(), reader.iterShapes()):
        zip_code = record["ZCTA5CE20"]
        if zip_code not in wanted:
            continue
        polygon = make_valid(shape(geometry.__geo_interface__))
        if polygon.is_empty:
            continue
        found[zip_code] = polygon
    reader.close()
    return found


def encode(features) -> bytes:
    payload = {
        "type": "FeatureCollection",
        "name": "alliance-service-areas",
        "source": "US Census Bureau 2020 cartographic ZCTA cb_2020_us_zcta520_500k. Alliance sheet ZIPs only. ZIPs with no census area are listed in missingZips and are not drawn.",
        "features": features,
    }
    return json.dumps(payload, separators=(",", ":"), ensure_ascii=False).encode()


def build_features(by_office: dict, zctas: dict, tolerance: float):
    features = []
    missing = {}
    for office, zips in by_office.items():
        present = [zctas[zip_code] for zip_code in zips if zip_code in zctas]
        absent = [zip_code for zip_code in zips if zip_code not in zctas]
        if absent:
            missing[office] = absent
        if not present:
            raise SystemExit(office + " has no ZCTA geometry")
        merged = unary_union(present)
        merged = make_valid(merged).simplify(tolerance, preserve_topology=True)
        merged = make_valid(set_precision(merged, 0.0001))
        if merged.is_empty:
            raise SystemExit(office + " disappeared at tolerance " + str(tolerance))
        features.append(
            {
                "type": "Feature",
                "properties": {
                    "id": office,
                    "zips": sorted(zip_code for zip_code in zips if zip_code in zctas),
                    "missingZips": absent,
                },
                "geometry": mapping(merged),
            }
        )
    return features, missing


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--shp", required=True, type=Path)
    args = parser.parse_args()
    by_office = load_alliance(ROUTING)
    wanted = {zip_code for zips in by_office.values() for zip_code in zips}
    zctas = load_zctas(args.shp, wanted)
    print(f"Matched {len(zctas)} of {len(wanted)} alliance ZIPs to a ZCTA polygon")

    chosen = None
    chosen_missing = None
    for tolerance in (0.001, 0.002, 0.003, 0.004, 0.006, 0.008, 0.01, 0.015):
        features, missing = build_features(by_office, zctas, tolerance)
        size = len(encode(features))
        print(f"tolerance {tolerance:.3f} -> {size} bytes")
        if size <= MAX_BYTES:
            chosen = features
            chosen_missing = missing
            break
    if chosen is None:
        raise SystemExit("Could not simplify the areas under 280 KB")

    body = encode(chosen)
    GEOJSON.write_bytes(body)
    LOADER.write_text(
        "// Generated by tools/build-service-areas.py. Do not edit by hand.\n"
        "// prettier-ignore\n"
        "const SERVICE_AREAS = "
        + body.decode()
        + ";\n"
    )
    print(f"Wrote {GEOJSON} ({len(body)} bytes)")
    if chosen_missing:
        print("ZIPs with no census polygon:")
        for office, zips in chosen_missing.items():
            print(f"  {office}: {', '.join(zips)}")
    else:
        print("Every alliance ZIP had a census polygon")


if __name__ == "__main__":
    main()
